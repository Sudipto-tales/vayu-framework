<?php

namespace Vayu\Console\Commands;

use Vayu\Console\Command;

/**
 * Compile every pure, array-returning config file into a single cached map so
 * the framework boots without stat-ing and require-ing each file.
 *
 * Only side-effect-free files are cached. Legacy config files that connect to a
 * database, run migrations, read superglobals or (re)declare functions are
 * detected statically and skipped — they are never required here.
 *
 * NOTE: env()-derived values are frozen at cache time (as in other frameworks).
 * Re-run `config:cache` after changing `.env`, or `config:clear` in development.
 */
class ConfigCacheCommand extends Command
{
    protected static string $name = 'config:cache';

    protected static string $description = 'Compile config files into a fast cached map';

    /** Function-like identifiers that mark a config file as side-effecting. */
    private const UNSAFE_CALLS = [
        'define', 'glob', 'exec', 'shell_exec', 'system', 'passthru',
        'proc_open', 'popen', 'putenv', 'pdo', 'mysqli', 'routemanager',
    ];

    /** Superglobals whose presence means the file depends on request state. */
    private const UNSAFE_VARS = [
        '$_SERVER', '$_GET', '$_POST', '$_REQUEST', '$_SESSION',
        '$_FILES', '$_COOKIE', '$GLOBALS',
    ];

    public function handle(array $args): int
    {
        $cached = [];
        $skipped = [];

        foreach (glob($this->app->configPath('*.php')) ?: [] as $file) {
            $name = basename($file, '.php');
            $source = (string) file_get_contents($file);

            if (!self::isCacheableSource($source)) {
                $skipped[] = $name;
                continue;
            }

            $value = self::loadIsolated($file);
            if (is_array($value)) {
                $cached[$name] = $value;
            } else {
                $skipped[] = $name;
            }
        }

        $cacheDir = $this->app->storagePath('cache');
        if (!is_dir($cacheDir)) {
            @mkdir($cacheDir, 0o775, true);
        }

        $cacheFile = $cacheDir . '/config.php';
        $export = "<?php\n\n// Generated by `php vayu config:cache` — do not edit.\n// Run `php vayu config:clear` to remove.\n\nreturn "
            . var_export($cached, true) . ";\n";

        if (file_put_contents($cacheFile, $export) === false) {
            $this->error('Could not write config cache to ' . $cacheFile);
            return 1;
        }

        $this->info('Configuration cached: ' . count($cached) . ' file(s).');
        $this->dim('  ' . implode(', ', array_keys($cached)));
        if ($skipped !== []) {
            $this->comment('Skipped (not cacheable / side-effecting): ' . implode(', ', $skipped));
        }

        return 0;
    }

    /**
     * True when a config file's source is safe to require at cache time: a pure
     * `return [...]` with no side effects. Uses PHP's tokenizer, so dangerous
     * words inside comments or string literals never cause a false skip, and a
     * file returning a closure (unserializable) is rejected via T_FUNCTION/T_FN.
     */
    public static function isCacheableSource(string $source): bool
    {
        $tokens = @token_get_all($source);
        if ($tokens === false) {
            return false;
        }

        $hasReturn = false;

        foreach ($tokens as $token) {
            if (!is_array($token)) {
                if ($token === '`') {
                    return false; // backtick shell execution
                }
                continue;
            }

            switch ($token[0]) {
                case T_RETURN:
                    $hasReturn = true;
                    break;
                case T_REQUIRE:
                case T_REQUIRE_ONCE:
                case T_INCLUDE:
                case T_INCLUDE_ONCE:
                case T_NEW:
                case T_EVAL:
                case T_FUNCTION:
                case T_FN:
                    return false;
                case T_STRING:
                    if (in_array(strtolower($token[1]), self::UNSAFE_CALLS, true)) {
                        return false;
                    }
                    break;
                case T_VARIABLE:
                    if (in_array($token[1], self::UNSAFE_VARS, true)) {
                        return false;
                    }
                    break;
            }
        }

        return $hasReturn;
    }

    /**
     * Require a file in an isolated scope so its local variables never leak.
     */
    private static function loadIsolated(string $file): mixed
    {
        return (static fn () => require $file)();
    }
}
